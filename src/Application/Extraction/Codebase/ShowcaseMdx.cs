    private const int MaxInlineSvgBytes = 8 * 1024;
    private const int MaxIconsRendered = 80;

    private const string RowStyle =
        "{ display: \"flex\", alignItems: \"center\", gap: 14, padding: \"4px 0\", fontSize: 12, fontFamily: \"monospace\" }";

    private const string NameStyle = "{ minWidth: 250, flexShrink: 0 }";

    private const string ValueStyle = "{ opacity: 0.7, marginLeft: \"auto\", textAlign: \"right\" }";

    private const string GeneratedBanner =
        "{/* Generated by figma_ds_scaffold — regenerate with the tool, do not edit by hand. */}";

    /// <summary>A string as a literal MDX can read: relaxed escaping keeps non-Latin text readable in the generated file.</summary>
    private static readonly JsonTypeInfo<string> RelaxedString = (JsonTypeInfo<string>)new JsonSerializerOptions
    {
        Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping,
        TypeInfoResolver = DsJsonContext.Default,
    }.GetTypeInfo(typeof(string));

    [GeneratedRegex(@"^cubic-bezier\(\s*(-?[\d.]+)[,\s]+(-?[\d.]+)[,\s]+(-?[\d.]+)[,\s]+(-?[\d.]+)\s*\)$")]
    private static partial Regex CubicBezierPattern();

    [GeneratedRegex(@"^(\d*\.?\d+)ms$")]
    private static partial Regex MillisecondsPattern();

    [GeneratedRegex(@"^(\d*\.?\d+)s$")]
    private static partial Regex SecondsPattern();

    [GeneratedRegex(@"^clamp\(|^calc\(")]
    private static partial Regex FluidValuePattern();

    [GeneratedRegex(@"text|font|size", RegexOptions.IgnoreCase)]
    private static partial Regex TypeSizeNamePattern();

    [GeneratedRegex(@"radius", RegexOptions.IgnoreCase)]
    private static partial Regex RadiusNamePattern();

    [GeneratedRegex(@"<svg[\s\S]*?</svg>", RegexOptions.IgnoreCase)]
    private static partial Regex FirstSvgPattern();

    [GeneratedRegex(@"-([a-z])")]
    private static partial Regex KebabSegmentPattern();

    [GeneratedRegex(@"h([1-6])\b")]
    private static partial Regex HeadingLevelPattern();

    [GeneratedRegex("display", RegexOptions.IgnoreCase)]
    private static partial Regex DisplaySelectorPattern();

    [GeneratedRegex("lead|subtitle", RegexOptions.IgnoreCase)]
    private static partial Regex LeadSelectorPattern();

    [GeneratedRegex("body|prose|text", RegexOptions.IgnoreCase)]
    private static partial Regex BodySelectorPattern();

    [GeneratedRegex("caption|eyebrow|overline", RegexOptions.IgnoreCase)]
    private static partial Regex CaptionSelectorPattern();

    [GeneratedRegex(@"(^|/)(font|text|type)(/|-)")]
    private static partial Regex TypographyPathPattern();

    [GeneratedRegex("font|text-")]
    private static partial Regex FontOrTextPathPattern();

