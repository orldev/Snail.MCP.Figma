    [GeneratedRegex(@"\s+")]
    private static partial Regex WhitespaceRunPattern();

    [GeneratedRegex("<svg", RegexOptions.IgnoreCase)]
    private static partial Regex SvgOpeningPattern();

    /// <summary>String into a JavaScript literal, like <c>JSON.stringify</c>.</summary>
    private static string Js(string? value) => JsonSerializer.Serialize(value ?? string.Empty, RelaxedString);

    /// <summary>MDX reads <c>{</c> as an expression and <c>&lt;</c> as a tag — both are escaped.</summary>
    private static string Escape(string value) =>
        value.Replace("{", "&#123;", StringComparison.Ordinal).Replace("<", "&lt;", StringComparison.Ordinal);

    private static string Number(double value) => value.ToString("0.#", CultureInfo.InvariantCulture);

    /// <summary>Resolves a value through the alias chain across all sets.</summary>
    private static Func<Token, (string Resolved, string? Via)> MakeResolver(TokenDocument document)
    {
        var byPath = new Dictionary<string, Token>(StringComparer.Ordinal);

        foreach (var token in document.AllTokens)
        {
            byPath.TryAdd(token.DottedPath, token);
        }

        return token =>
        {
            Token? current = token;
            string? via = null;

            for (var depth = 0; depth < 6 && current is not null; depth++)
            {
                var value = current.Values.Values.FirstOrDefault();

                if (value is null)
                {
                    break;
                }

                if (value.IsReference)
                {
                    var reference = value.Reference!.Trim('{', '}');
                    via ??= reference;
                    current = byPath.GetValueOrDefault(reference);
                    continue;
                }

                var literal = value.Literal switch
                {
                    null => string.Empty,
                    JsonValue json when json.TryGetValue<string>(out var text) => text,
                    var other => other.ToJsonString(),
                };

                return (literal, via);
            }

            return (via is null ? string.Empty : $"{{{via}}}", via);
        };
    }

    /// <summary>Tiny SVG easing curve for <c>cubic-bezier</c> values.</summary>
    private static string? EasingCurveSvg(string value)
    {
        var match = CubicBezierPattern().Match(value.Trim());

        if (!match.Success)
        {
            return null;
        }

        var points = Enumerable.Range(1, 4)
            .Select(i => double.Parse(match.Groups[i].Value, NumberStyles.Float, CultureInfo.InvariantCulture))
            .ToArray();

        const int size = 40;

        string X(double x) => (x * size).ToString("0.0", CultureInfo.InvariantCulture);

        string Y(double y) => (size - (y * size)).ToString("0.0", CultureInfo.InvariantCulture);

        return string.Concat(
            $"<svg width={{{size}}} height={{{size}}} viewBox=\"0 0 {size} {size}\" style={{{{ overflow: \"visible\" }}}}>",
            $"<rect width={{{size}}} height={{{size}}} fill=\"none\" stroke=\"#8886\" rx={{4}} />",
            $"<path d=\"M 0 {size} C {X(points[0])} {Y(points[1])}, {X(points[2])} {Y(points[3])}, {size} 0\" ",
            "fill=\"none\" stroke=\"var(--sl-accent, #f05735)\" strokeWidth={2} />",
            "</svg>");
    }

    public static string TokenShowcase(TokenDocument document)
    {
        var resolve = MakeResolver(document);
        var lines = new List<string>
        {
            GeneratedBanner,
            string.Empty,
            "import { Meta } from '@storybook/addon-docs/blocks';",
            string.Empty,
            "<Meta title=\"Design Tokens/Overview\" />",
            string.Empty,
            "# Design Tokens",
            string.Empty,
            "Mined from the codebase. Structural names as found; semantic names are layered on with the team. Provenance of every token lives in `tokens/tokens.json` under `$extensions`.",
            string.Empty,
        };

        void PushRow(Token token, string middle, string valueText) =>
            lines.Add(
                $"<div style={{{RowStyle}}}><code style={{{NameStyle}}}>{Escape(token.SlashPath)}</code>{middle}<span style={{{ValueStyle}}}>{Escape(valueText)}</span></div>");

        foreach (var set in document.Sets)
        {
            lines.Add($"## {set.Name}");
            lines.Add(string.Empty);

            if (!string.IsNullOrWhiteSpace(set.Description))
            {
                lines.Add(set.Description);
                lines.Add(string.Empty);
            }

            foreach (var group in set.Tokens.GroupBy(t => t.Type, StringComparer.Ordinal))
            {
                var tokens = group.ToList();
                lines.Add($"### {group.Key} ({tokens.Count})");
                lines.Add(string.Empty);

                if (group.Key == TokenTypes.Color)
                {
                    lines.Add("<div style={{ display: \"flex\", flexWrap: \"wrap\", gap: 12 }}>");

                    foreach (var token in tokens)
                    {
                        var (resolved, via) = resolve(token);
                        var caption = via is null ? resolved : $"→ {via}";
                        lines.Add("  <div style={{ width: 150 }}>");
                        lines.Add(
                            $"    <div style={{{{ height: 48, borderRadius: 6, border: \"1px solid #8886\", background: {Js(resolved.Length > 0 ? resolved : "transparent")} }}}} />");
                        lines.Add($"    <code style={{{{ fontSize: 11 }}}}>{Escape(token.SlashPath)}</code><br />");
                        lines.Add($"    <span style={{{{ fontSize: 11, opacity: 0.7 }}}}>{Escape(caption)}</span>");
                        lines.Add("  </div>");
                    }

                    lines.Add("</div>");
                    lines.Add(string.Empty);
                    continue;
                }

                foreach (var token in tokens)
                {
                    var (resolved, via) = resolve(token);
                    var valueText = via is null ? resolved : $"{resolved}  (→ {via})";
                    var path = token.SlashPath;
                    var px = CodeTokenExtractor.ApproximatePixels(resolved);

                    if (group.Key == TokenTypes.Dimension && RadiusNamePattern().IsMatch(path) && px is not null)
                    {
                        PushRow(
                            token,
                            $"<div style={{{{ width: 44, height: 32, borderRadius: {Js(resolved)}, background: \"color-mix(in srgb, var(--sl-accent, #f05735) 30%, transparent)\", border: \"1.5px solid var(--sl-accent, #f05735)\", flexShrink: 0 }}}} />",
                            valueText);
                    }
                    else if (group.Key == TokenTypes.Dimension && px is not null)
                    {
                        var bar = Math.Max(3, Math.Min(240, px.Value));
                        PushRow(
                            token,
                            $"<div style={{{{ width: {Number(Math.Round(bar))}, height: 10, borderRadius: 2, background: \"var(--sl-accent, #f05735)\", opacity: 0.75, flexShrink: 0 }}}} />",
                            valueText);
                    }
                    else if (group.Key == TokenTypes.Shadow)
                    {
                        PushRow(
                            token,
                            $"<div style={{{{ width: 44, height: 32, borderRadius: 6, background: \"var(--sl-bg-raised, #fff)\", boxShadow: {Js(resolved)}, flexShrink: 0 }}}} />",
                            valueText);
                    }
                    else if (group.Key == TokenTypes.Duration)
                    {
                        var milliseconds = MillisecondsPattern().Match(resolved.Trim()) is { Success: true } ms
                            ? double.Parse(ms.Groups[1].Value, NumberStyles.Float, CultureInfo.InvariantCulture)
                            : SecondsPattern().Match(resolved.Trim()) is { Success: true } s
                                ? double.Parse(s.Groups[1].Value, NumberStyles.Float, CultureInfo.InvariantCulture) * 1000
                                : (double?)null;
                        var bar = milliseconds is null ? 3 : Math.Max(4, Math.Min(240, milliseconds.Value / 4));

                        PushRow(
                            token,
                            $"<div style={{{{ width: {Number(Math.Round(bar))}, height: 10, borderRadius: 2, background: \"var(--sl-link, #2e8bbd)\", opacity: 0.75, flexShrink: 0 }}}} />",
                            valueText);
                    }
                    else if (EasingCurveSvg(resolved) is { } curve)
                    {
                        PushRow(token, curve, valueText);
                    }
                    else if (group.Key == TokenTypes.FontFamily)
                    {
                        PushRow(
                            token,
                            $"<span style={{{{ fontFamily: {Js(resolved)}, fontSize: 22, lineHeight: 1, flexShrink: 0 }}}}>Ag</span>",
                            valueText);
                    }
                    else if (FluidValuePattern().IsMatch(resolved) && TypeSizeNamePattern().IsMatch(path))
                    {
                        PushRow(
                            token,
                            $"<span style={{{{ fontSize: {Js(resolved)}, lineHeight: 1, whiteSpace: \"nowrap\", overflow: \"hidden\", textOverflow: \"ellipsis\", maxWidth: 380 }}}}>Ag</span>",
                            valueText);
                    }
                    else
                    {
                        PushRow(token, string.Empty, valueText);
                    }
                }

                lines.Add(string.Empty);
            }
        }

        return $"{string.Join('\n', lines)}\n";
    }

    private static string CssPropertiesToJsxStyle(IReadOnlyDictionary<string, string> properties)
    {
        var entries = properties.Select(pair =>
        {
            var camel = KebabSegmentPattern().Replace(pair.Key, m => m.Groups[1].Value.ToUpperInvariant());

            return $"{camel}: {Js(pair.Value)}";
        });

        return $"{{ {string.Join(", ", entries)} }}";
    }

    /// <summary>Rank of a typography selector so the hierarchy reads top-down.</summary>
    private static int TypographyRank(string selector)
    {
        if (DisplaySelectorPattern().IsMatch(selector)) return 0;
        if (HeadingLevelPattern().Match(selector) is { Success: true } heading) return int.Parse(heading.Groups[1].Value);
        if (LeadSelectorPattern().IsMatch(selector)) return 7;
        if (BodySelectorPattern().IsMatch(selector)) return 8;
        if (CaptionSelectorPattern().IsMatch(selector)) return 9;

        return 10;
    }

    public static string TypographyShowcase(TokenDocument document, IReadOnlyList<DsTypographyRule> rules)
    {
        var lines = new List<string>
        {
            GeneratedBanner,
            string.Empty,
            "import { Meta } from '@storybook/addon-docs/blocks';",
            string.Empty,
            "<Meta title=\"Design Tokens/Typography\" />",
            string.Empty,
            "# Typography",
            string.Empty,
            "Scale, families and heading hierarchy as applied in the source codebase.",
            string.Empty,
        };

        var fontTokens = document.AllTokens
            .Where(token =>
            {
                var path = token.SlashPath;

                return token.Type == TokenTypes.FontFamily
                    || TypographyPathPattern().IsMatch(path)
                    || FontOrTextPathPattern().IsMatch(path);
            })
            .ToList();

        if (fontTokens.Count > 0)
        {
            lines.Add("## Type tokens");
            lines.Add(string.Empty);

            foreach (var family in fontTokens.Where(t => t.Type == TokenTypes.FontFamily))
            {
                var value = TokenFileWriter.FirstLiteral(family);
                lines.Add("<div style={{ margin: \"12px 0\" }}>");
                lines.Add($"  <code style={{{{ fontSize: 12 }}}}>{Escape(family.SlashPath)}</code>");
                lines.Add($"  <div style={{{{ fontFamily: {Js(value)}, fontSize: 28 }}}}>Aa Bb Cc — {Escape(value)}</div>");
                lines.Add("</div>");
            }

            var sizes = fontTokens
                .Where(t => t.Type != TokenTypes.FontFamily
                    && TypeScalePathPattern().IsMatch(t.SlashPath))
                .ToList();

            if (sizes.Count > 0)
            {
                lines.Add(string.Empty);
                lines.Add("### Scale");
                lines.Add(string.Empty);

                foreach (var token in sizes)
                {
                    var value = TokenFileWriter.FirstLiteral(token);

                    if (value.Length == 0 || value.StartsWith('{'))
                    {
                        continue;
                    }

                    lines.Add("<div style={{ display: \"flex\", alignItems: \"baseline\", gap: 16, margin: \"8px 0\" }}>");
                    lines.Add($"  <code style={{{{ fontSize: 11, minWidth: 220 }}}}>{Escape(token.SlashPath)}</code>");
                    lines.Add(
                        $"  <span style={{{{ fontSize: {Js(value)}, lineHeight: 1.1, whiteSpace: \"nowrap\", overflow: \"hidden\", textOverflow: \"ellipsis\" }}}}>The quick brown fox</span>");
                    lines.Add("</div>");
                }
            }

            lines.Add(string.Empty);
        }

        if (rules.Count > 0)
        {
            lines.Add("## Applied hierarchy & classes");
            lines.Add(string.Empty);
            lines.Add("Selectors from the application stylesheets, shown with their real declarations:");
            lines.Add(string.Empty);

            foreach (var rule in rules.OrderBy(r => TypographyRank(r.Selector)).Take(40))
            {
                var declarations = string.Join("; ", rule.Properties.Select(p => $"{p.Key}: {p.Value}"));
                lines.Add("<div style={{ margin: \"14px 0\", borderBottom: \"1px solid #8884\", paddingBottom: 10 }}>");
                lines.Add($"  <code style={{{{ fontSize: 11 }}}}>{Escape(rule.Selector)}</code>");
                lines.Add($"  <span style={{{{ fontSize: 10, opacity: 0.6 }}}}> — {Escape(rule.Source)}</span>");
                lines.Add($"  <div style={{{CssPropertiesToJsxStyle(rule.Properties)}}}>The quick brown fox jumps over the lazy dog</div>");
                lines.Add(
                    $"  <div style={{{{ fontSize: 10, fontFamily: \"monospace\", opacity: 0.7, marginTop: 4 }}}}>{Escape(declarations)}</div>");
                lines.Add("</div>");
            }

            lines.Add(string.Empty);
        }

        return $"{string.Join('\n', lines)}\n";
    }

    private static string? ExtractFirstSvg(string text)
    {
        var match = FirstSvgPattern().Match(text);

        if (!match.Success || match.Value.Length > MaxInlineSvgBytes)
        {
            return null;
        }

        return match.Value.Contains('{', StringComparison.Ordinal) ? null : match.Value;
    }

    public static string IconShowcase(IReadOnlyList<(DsIconEntry Icon, string Root)> entries)
    {
        var lines = new List<string>
        {
            GeneratedBanner,
            string.Empty,
            "import { Meta } from '@storybook/addon-docs/blocks';",
            string.Empty,
            "<Meta title=\"Design Tokens/Iconography\" />",
            string.Empty,
            "# Iconography",
            string.Empty,
            "SVG assets and components with inline SVG found in the source codebase.",
            string.Empty,
            "<div style={{ display: \"flex\", flexWrap: \"wrap\", gap: 16 }}>",
        };

        var rendered = 0;
        var unrenderable = new List<DsIconEntry>();
        var seen = new HashSet<string>(StringComparer.Ordinal);

        foreach (var (icon, root) in entries)
        {
            if (rendered >= MaxIconsRendered)
            {
                break;
            }

            var raw = CodeWalker.ReadText(Path.Combine(root, icon.File.Replace('/', Path.DirectorySeparatorChar)));
            var svg = raw is null ? null : ExtractFirstSvg(raw);

            if (svg is null)
            {
                unrenderable.Add(icon);
                continue;
            }

            if (!seen.Add(WhitespaceRunPattern().Replace(svg, " ")))
            {
                continue;
            }

            rendered++;

            var sized = SvgOpeningPattern().Replace(
                svg,
                "<svg style=\"width:100%;height:100%\" preserveAspectRatio=\"xMidYMid meet\"");

            string Panel(string background) =>
                $"      <div style={{{{ flex: 1, background: {Js(background)}, padding: 6, height: \"100%\", boxSizing: \"border-box\" }}}} dangerouslySetInnerHTML={{{{ __html: {Js(sized)} }}}} />";

            lines.Add("  <div style={{ width: 170, textAlign: \"center\" }}>");
            lines.Add("    <div style={{ height: 56, border: \"1px solid #8884\", borderRadius: 6, overflow: \"hidden\", display: \"flex\" }}>");
            lines.Add(Panel("#181714"));
            lines.Add(Panel("#f3f1eb"));
            lines.Add("    </div>");
            lines.Add($"    <code style={{{{ fontSize: 10 }}}}>{Escape(icon.Name)}</code>");
            lines.Add("  </div>");
        }

        lines.Add("</div>");
        lines.Add(string.Empty);

        if (unrenderable.Count > 0)
        {
            lines.Add("## Not rendered (dynamic or too large)");
            lines.Add(string.Empty);

            foreach (var icon in unrenderable.Take(60))
            {
                lines.Add($"- {Escape(icon.Name)} — `{Escape(icon.File)}` ({icon.Source})");
            }

            lines.Add(string.Empty);
        }

        return $"{string.Join('\n', lines)}\n";
    }
